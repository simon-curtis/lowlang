type xxhAccumulator [8]uint64

func newXXHAccumulator() xxhAccumulator {
	return xxhAccumulator{
		xxhPrime32x3, xxhPrime64x1, xxhPrime64x2, xxhPrime64x3,
		xxhPrime64x4, xxhPrime32x2, xxhPrime64x5, xxhPrime32x1,
	}
}

func (a *xxhAccumulator) stripe(input []byte, secret []byte) {
	for i := range a {
		value := binary.LittleEndian.Uint64(input[8*i:])
		key := value ^ binary.LittleEndian.Uint64(secret[8*i:])
		a[i^1] += value
		a[i] += (key & 0xFFFFFFFF) * (key >> 32)
	}
}

func (a *xxhAccumulator) scramble(secret []byte) {
	for i := range a {
		value := a[i]
		value ^= value >> 47
		value ^= binary.LittleEndian.Uint64(secret[8*i:])
		a[i] = value * xxhPrime32x1
	}
}

func (a *xxhAccumulator) merge(secret []byte, start uint64) uint64 {
	result := start
	for i := 0; i < 4; i++ {
		low := a[2*i] ^ binary.LittleEndian.Uint64(secret[16*i:])
		high := a[2*i+1] ^ binary.LittleEndian.Uint64(secret[16*i+8:])
		hi, lo := bits.Mul64(low, high)
		result += hi ^ lo
	}
	result ^= result >> 37
	result *= xxhMix1
	return result ^ result>>32
}

func xxh3Long(data []byte) uint64 {
	secret := xxhSecret[:]
	acc := newXXHAccumulator()
	stripesPerBlock := (len(secret) - xxhStripe) / xxhSecretStep
	blockSize := xxhStripe * stripesPerBlock
	blocks := (len(data) - 1) / blockSize
	for b := 0; b < blocks; b++ {
		block := data[b*blockSize:]
		for s := 0; s < stripesPerBlock; s++ {
			acc.stripe(block[s*xxhStripe:], secret[s*xxhSecretStep:])
		}
		acc.scramble(secret[len(secret)-xxhStripe:])
	}
	tail := data[blocks*blockSize:]
	stripes := (len(data) - 1 - blocks*blockSize) / xxhStripe
	for s := 0; s < stripes; s++ {
		acc.stripe(tail[s*xxhStripe:], secret[s*xxhSecretStep:])
	}
	acc.stripe(data[len(data)-xxhStripe:], secret[len(secret)-xxhStripe-xxhSecretLast:])
	return acc.merge(secret[xxhSecretMerge:], uint64(len(data))*xxhPrime64x1)
}
